package org.mr0btain.ticketman.logging

import platform.Foundation.NSRecursiveLock

internal actual class LogLock actual constructor() {
    private val lock = NSRecursiveLock()

    actual fun <T> withLock(block: () -> T): T {
        lock.lock()
        try {
            return block()
        } finally {
            lock.unlock()
        }
    }
}
